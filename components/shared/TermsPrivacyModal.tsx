// ----- Modal Component -----

interface TermsPrivacyModalProps {
  /**
   * Render prop: receives the openModal callback and returns the trigger element.
   * Example usage in CitizenAuthOptions:
   *   trigger={(open) => <button type="button" onClick={open}>Terms of Use & Privacy Notice</button>}
   */
  trigger: (openModal: () => void) => React.ReactNode;
}

export function TermsPrivacyModal({ trigger }: TermsPrivacyModalProps) {
  const [isOpen, setIsOpen] = useState(false);
  const dialogRef = useRef<HTMLDialogElement>(null);
  const titleId = useId();
  const closeBtnRef = useRef<HTMLButtonElement>(null);

  function openModal() {
    setIsOpen(true);
  }

  function closeModal() {
    setIsOpen(false);
  }

  // Sync React state with the native dialog element
  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;
    if (isOpen) {
      if (!dialog.open) {
        dialog.showModal();
      }
      // Move focus to the X button after opening
      closeBtnRef.current?.focus();
    } else {
      if (dialog.open) {
        dialog.close();
      }
    }
  }, [isOpen]);

  useEffect(() => {
    if (!isOpen) return;
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = previousOverflow;
    };
  }, [isOpen]);

  // Handle native close (Escape key)
  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;
    function onNativeClose() {
      setIsOpen(false);
    }
    dialog.addEventListener("close", onNativeClose);
    return () => dialog.removeEventListener("close", onNativeClose);
  }, []);

  // Click on the backdrop (the dialog element itself) closes the modal
  function handleDialogClick(e: React.MouseEvent<HTMLDialogElement>) {
    if (e.target === dialogRef.current) {
      closeModal();
    }
  }

  return (
    <>
      {trigger(openModal)}

      <dialog
        ref={dialogRef}
        className="tpm-dialog"
        aria-labelledby={titleId}
        aria-modal="true"
        onClick={handleDialogClick}
      >
        {/* ---- Header ---- */}
        <div className="tpm-header">
          <div className="tpm-header-inner">
            <span className="tpm-icon" aria-hidden="true">
              <FileText />
            </span>
            <div>
              <h2 id={titleId} className="tpm-title">
                AfyaPulse Terms of Use &amp; Privacy Notice
              </h2>
              <p className="tpm-subtitle">Last updated: {LAST_UPDATED}</p>
            </div>
          </div>
          <button
            ref={closeBtnRef}
            type="button"
            className="tpm-close-x"
            aria-label="Close Terms of Use & Privacy Notice"
            onClick={closeModal}
          >
            <X aria-hidden="true" />
          </button>
        </div>

        {/* ---- Scrollable body ---- */}
        <div className="tpm-body" tabIndex={0} role="region" aria-label="Terms and privacy notice content">
          <p className="tpm-intro">
            Welcome to AfyaPulse, an early health signal and public-health
            awareness platform designed to help individuals understand their
            health information while supporting privacy-conscious community
            health surveillance.
          </p>
          <p className="tpm-intro">
            By creating an AfyaPulse account or using the platform, you
            acknowledge that you have read and understood these Terms of Use
            and Privacy Notice.
          </p>

          {POLICY_SECTIONS.map((section) => (
            <section key={section.heading} className="tpm-section">
              <h3 className="tpm-section-heading">{section.heading}</h3>
              {section.body.map((para, i) => (
                <p key={i} className="tpm-para">
                  {para}
                </p>
              ))}
              {section.list && (
                <ul className="tpm-list">
                  {section.list.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              )}
              {section.bodyAfter?.map((para, i) => (
                <p key={`after-${i}`} className="tpm-para">
                  {para}
                </p>
              ))}
            </section>
          ))}

          {/* ---- Acknowledgement notice at bottom ---- */}
          <div className="tpm-ack">
            <p>
              By selecting &ldquo;I acknowledge the Terms of Use &amp; Privacy
              Notice&rdquo; and creating an account, you confirm that you have
              had an opportunity to read this notice and agree to the AfyaPulse
              Terms of Use.
            </p>
            <p>
              Optional community health contribution remains a separate choice
              and is not required simply to create an AfyaPulse account.
            </p>
          </div>
        </div>

        {/* ---- Footer ---- */}
        <div className="tpm-footer">
          <button
            type="button"
            className="tpm-close-action"
            onClick={closeModal}
          >
            Close
          </button>
        </div>
      </dialog>
    </>
  );
}
